# Import camera and display modules
import camera
import display

# Step 1: Start the camera
# ✏️ INITIALIZE THE CAMERA
# __BLANK__ capture_camera = camera.Init_Camera()

print("[OK] Color variations ready!")

# Step 2: Draw colored shapes
while True:
    # ✏️ IN THE LOOP, GET A FRAME
    # __BLANK__ camera_frame = camera.Get_Camera_Frame(capture_camera = capture_camera)

    # ✏️ DRAW 4 CIRCLES WITH DIFFERENT COLORS: GREEN, RED, BLUE, YELLOW
    # __BLANK__ camera_frame = display.Draw_Circle(camera_frame = camera_frame, center_x = 100, center_y = 100, radius = 50, color = "green")

    # ✏️ EACH CIRCLE AT A DIFFERENT POSITION
    # __BLANK__ camera_frame = display.Draw_Circle(camera_frame = camera_frame, center_x = 540, center_y = 100, radius = 50, color = "red")

    # ✏️ DISPLAY THE IMAGE
    # __BLANK__ camera_frame = display.Draw_Circle(camera_frame = camera_frame, center_x = 100, center_y = 380, radius = 50, color = "blue")

    # ✏️ CLOSE THE CAMERA
    # __BLANK__ camera_frame = display.Draw_Circle(camera_frame = camera_frame, center_x = 540, center_y = 380, radius = 50, color = "yellow")

    # __BLANK__ display.Show_Image(camera_frame = camera_frame)

# Step 3: Clean up
# __BLANK__ camera.Close_Camera(capture_camera = capture_camera)

    pass  # Placeholder for blank lines