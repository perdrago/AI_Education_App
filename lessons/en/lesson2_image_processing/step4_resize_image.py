# Import camera, image processing, and display modules
import camera
import image
import display

# Step 1: Start the camera
# ✏️ INITIALIZE THE CAMERA
# __BLANK__ capture_camera = camera.Init_Camera()

print("[OK] Resize ready!")

# Step 2: Resize in loop
while True:
    # ✏️ IN THE LOOP, GET A FRAME
    # __BLANK__ camera_frame = camera.Get_Camera_Frame(capture_camera = capture_camera)

    # ✏️ USE `RESIZE_IMAGE()` WITH `WIDTH=320`, `HEIGHT=240` TO SHRINK THE IMAGE
    # __BLANK__ resized_frame = image.resize_image(input_image = camera_frame, width = 320, height = 240)

    # ✏️ DISPLAY THE RESIZED IMAGE
    # __BLANK__ display.Show_Image(camera_frame = resized_frame)

# Step 3: Clean up
# ✏️ CLOSE THE CAMERA
# __BLANK__ camera.Close_Camera(capture_camera = capture_camera)

    pass  # Placeholder for blank lines